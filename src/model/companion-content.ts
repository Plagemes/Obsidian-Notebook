/**
 * Companion note content (O1): a notebook document → Markdown properties and a generated body region,
 * and the merge of that content into a note the user may have edited. Pure: no 'obsidian'.
 *
 * Designed for the M4 container change: if notebooks become `.md` files, `companionContent()` gives the
 * notebook's own frontmatter and generated body unchanged; only the file location (storage/companion-path.ts)
 * and the service that writes the companion (integration/companion.ts) go away.
 *
 * Ownership rules (see docs/architecture.md §12):
 * - plugin-owned properties are overwritten on every update and removed when the notebook no longer has a value;
 * - `tags` is shared: the notebook's tags are added, tags the user added are kept, tags the plugin added
 *   earlier and the notebook no longer has are removed;
 * - every other property and everything outside the generated region belong to the user and are never touched;
 * - the generated region (between the start and end markers) is replaced as a whole.
 *
 * The output depends only on the document and the notebook path (no clock, time zone, language or vault
 * name), so two synced devices generate byte-identical notes and never rewrite each other's copy.
 */
import { computeSharedTags, normalizeTag, uniqueTags } from "./tags";
import type { NotebookDocument, TextElement } from "./types";

export const COMPANION_LINK_KEY = "notebook";
export const COMPANION_ID_KEY = "notebook-id";
export const COMPANION_PAGES_KEY = "pages";
export const COMPANION_CREATED_KEY = "created";
export const COMPANION_MODIFIED_KEY = "modified";
export const TAGS_KEY = "tags";

/** Properties always written, in this order, before the ones that come from the notebook's `meta`. */
export const FIXED_KEYS: readonly string[] = [COMPANION_LINK_KEY, COMPANION_ID_KEY, COMPANION_PAGES_KEY, COMPANION_CREATED_KEY, COMPANION_MODIFIED_KEY];

/** Start marker prefix (an Obsidian comment: hidden in reading view). The rest of the line holds the region state. */
export const REGION_START = "%% notebook-companion:start";
export const REGION_END = "%% notebook-companion:end %%";
const REGION_NOTE = "(generated by Notebook: edit outside this block)";

export type PropertyValue = string | number | boolean | Array<string | number>;
export type Properties = Record<string, PropertyValue>;

export interface CompanionContext {
	/** Vault path of the notebook (in M4: of the note itself). */
	notebookPath: string;
	/** Link that opens the notebook at a 1-based page, by page id first (integration/links.ts `notebookUri`). */
	pageUri(page: number, pageId?: string): string;
}

export interface CompanionContent {
	/** Plugin-owned properties, in output order. Never contains `tags`. */
	properties: Properties;
	/** The notebook's tags, as Obsidian tags. */
	tags: string[];
	/** Generated Markdown (between the markers). */
	text: string;
}

/** What the plugin wrote last time, stored on the start marker line so the next update knows what it owns. */
export interface RegionState {
	keys: string[];
	/** Tags the plugin added to the note (not the ones the person wrote): the only tags it may remove later. */
	tags: string[];
}

// ------------------------------------------------------------------- generator

/** Minute precision, UTC, ISO 8601 (`2026-10-29T14:42:00Z`): stable across time zones, changes at most once a minute. */
export function companionTime(iso: unknown): string | null {
	const ms = typeof iso === "string" ? Date.parse(iso) : NaN;
	if (!Number.isFinite(ms)) return null;
	return `${new Date(Math.floor(ms / 60_000) * 60_000).toISOString().slice(0, 16)}:00Z`;
}

/**
 * A notebook tag as an Obsidian tag: no leading `#`, spaces become `-`, characters Obsidian does not allow
 * in tags are dropped, nested tags are `a/b`; purely numeric tags are not valid Obsidian tags and give null.
 * (The same function the tag editor uses, so what the person sees is what the note gets: model/tags.ts.)
 */
export const obsidianTag: (raw: string) => string | null = normalizeTag;

function propertyValue(v: unknown): PropertyValue | null {
	if (typeof v === "string") return v.trim() ? v : null;
	if (typeof v === "boolean") return v;
	if (typeof v === "number") return Number.isFinite(v) ? v : null;
	if (Array.isArray(v)) {
		const items = v.filter((x): x is string | number => (typeof x === "string" && x.trim().length > 0) || (typeof x === "number" && Number.isFinite(x)));
		return items.length > 0 ? items : null;
	}
	return null;
}

/**
 * Escapes one line of text-box text so it stays plain text inside the region: it can never close the
 * region (`%%`), open a block that would swallow what follows (code fence, math block, HTML comment),
 * or turn into a heading, a heading underline, a rule or an HTML block. Links (`[[…]]`) and inline tags are kept on purpose.
 */
export function escapeLine(line: string): string {
	const s = line.replace(/\s+$/, "").replace(/%%/g, "%\\%");
	const block = /^\s{0,3}(```|~~~|\$\$|<[A-Za-z!?/]|#{1,6}(\s|$))/.test(s)
		|| /^\s{0,3}(-+|=+|\*{3,}|_{3,})\s*$/.test(s)
		|| /^\s{0,3}([-*_])(\s+\1){2,}\s*$/.test(s);
	return block ? s.replace(/^(\s*)/, "$1\\") : s;
}

function textBlocks(elements: readonly unknown[] | undefined): string[] {
	const texts = (elements ?? []).filter((e): e is TextElement =>
		typeof e === "object" && e !== null && (e as TextElement).type === "text" && typeof (e as TextElement).text === "string");
	// Reading order: top to bottom, then left to right; stable for equal positions.
	const ordered = texts.map((e, i) => ({ e, i })).sort((a, b) =>
		(Number(a.e.y) || 0) - (Number(b.e.y) || 0) || (Number(a.e.x) || 0) - (Number(b.e.x) || 0) || a.i - b.i);
	const out: string[] = [];
	for (const { e } of ordered) {
		const lines = e.text.replace(/\r\n?/g, "\n").split("\n").map(escapeLine);
		while (lines.length > 0 && lines[0] === "") lines.shift();
		while (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
		// Several empty lines in a row would end the paragraph anyway: one is enough.
		const compact = lines.filter((l, i) => l !== "" || lines[i - 1] !== "");
		if (compact.length > 0) out.push(compact.join("\n"));
	}
	return out;
}

/** Page heading in the region; language-neutral so two devices in different languages write the same note. */
export function pageHeading(page: number): string {
	return `p. ${page}`;
}

/** Properties, tags and generated text for a notebook. */
export function companionContent(doc: NotebookDocument, ctx: CompanionContext): CompanionContent {
	const pages = Array.isArray(doc.pages) ? doc.pages : [];
	const name = ctx.notebookPath.slice(ctx.notebookPath.lastIndexOf("/") + 1).replace(/\.[^.]+$/, "");
	const properties: Properties = {
		[COMPANION_LINK_KEY]: `[[${ctx.notebookPath}|${name}]]`,
		[COMPANION_ID_KEY]: String(doc.id),
		[COMPANION_PAGES_KEY]: pages.length,
	};
	const created = companionTime(doc.createdAt);
	const modified = companionTime(doc.modifiedAt);
	if (created) properties[COMPANION_CREATED_KEY] = created;
	if (modified) properties[COMPANION_MODIFIED_KEY] = modified;

	// Everything in `meta` (course, teacher… once the format has them), as is; tags and bookmarks are special.
	const meta = (typeof doc.meta === "object" && doc.meta !== null ? doc.meta : {}) as unknown as Record<string, unknown>;
	const tags: string[] = [];
	for (const [key, raw] of Object.entries(meta)) {
		if (key === TAGS_KEY) {
			for (const t of Array.isArray(raw) ? raw : []) {
				const tag = typeof t === "string" ? obsidianTag(t) : null;
				if (tag) tags.push(tag);
			}
			continue;
		}
		if (FIXED_KEYS.includes(key) || !/^[A-Za-z][\w-]*$/.test(key)) continue;
		if (key === "bookmarks") {
			const ids = new Set(Array.isArray(raw) ? raw : []);
			const numbers = pages.flatMap((p, i) => (ids.has(p?.id) ? [i + 1] : []));
			if (numbers.length > 0) properties[key] = numbers;
			continue;
		}
		// v7 bookmark details (titles, colours, categories) belong to the outline, not to the note's properties.
		if (key === "bookmarkInfo") continue;
		const value = propertyValue(raw);
		if (value !== null) properties[key] = value;
	}

	const sections: string[] = [];
	pages.forEach((page, i) => {
		const blocks = textBlocks(page?.elements);
		if (blocks.length === 0) return;
		// Parentheses would end the Markdown link early.
		const uri = ctx.pageUri(i + 1, page.id).replace(/\(/g, "%28").replace(/\)/g, "%29");
		sections.push([`### ${pageHeading(i + 1)}`, `[↗ ${pageHeading(i + 1)}](${uri})`, "", blocks.join("\n\n")].join("\n"));
	});
	return { properties, tags: uniqueTags(tags), text: sections.join("\n\n") };
}

// ------------------------------------------------------------------- region

/**
 * The generated region, markers included, with the state the next update needs. `ownedTags` are the tags the plugin
 * added to the note (default: all of the notebook's, as for a new note); only those may be removed again later.
 */
export function renderRegion(content: CompanionContent, ownedTags: readonly string[] = content.tags): string {
	const state: RegionState = { keys: Object.keys(content.properties), tags: [...ownedTags] };
	// `%` is escaped so a tag can never end the comment early.
	const json = JSON.stringify({ v: 1, ...state }).replace(/%/g, "\\u0025");
	const start = `${REGION_START} ${REGION_NOTE} ${json} %%`;
	return content.text ? `${start}\n${content.text}\n${REGION_END}` : `${start}\n${REGION_END}`;
}

type RegionLines = { kind: "none" } | { kind: "broken" } | { kind: "ok"; start: number; end: number };

function findRegion(lines: readonly string[]): RegionLines {
	const starts: number[] = [];
	const ends: number[] = [];
	lines.forEach((l, i) => {
		const t = l.trim();
		if (t.startsWith(REGION_START)) starts.push(i);
		else if (t === REGION_END) ends.push(i);
	});
	if (starts.length === 0 && ends.length === 0) return { kind: "none" };
	if (starts.length !== 1 || ends.length !== 1 || ends[0]! < starts[0]!) return { kind: "broken" };
	return { kind: "ok", start: starts[0]!, end: ends[0]! };
}

/** `none`: no region yet; `broken`: markers missing, repeated or out of order (the note is then left alone). */
export function regionStatus(text: string): "none" | "broken" | "ok" {
	return findRegion(text.split(/\r?\n/)).kind;
}

/** State stored on the start marker, or null when there is no readable region. */
export function readRegionState(text: string): RegionState | null {
	const lines = text.split(/\r?\n/);
	const region = findRegion(lines);
	if (region.kind !== "ok") return null;
	const line = lines[region.start]!;
	const open = line.indexOf("{");
	const close = line.lastIndexOf("}");
	if (open < 0 || close < open) return null;
	try {
		const data = JSON.parse(line.slice(open, close + 1)) as { keys?: unknown; tags?: unknown };
		const strings = (v: unknown) => (Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : []);
		return { keys: strings(data.keys), tags: strings(data.tags) };
	} catch {
		return null;
	}
}

/**
 * The note text with the generated region replaced (or appended at the end when the note has none).
 * Returns null when the markers are broken: the note is not touched rather than guessing what is the user's.
 * Line endings of the note are kept.
 */
export function mergeRegion(text: string, region: string): string | null {
	const eol = text.includes("\r\n") ? "\r\n" : "\n";
	const lines = text.split(/\r?\n/);
	const found = findRegion(lines);
	const regionLines = region.split("\n");
	if (found.kind === "broken") return null;
	if (found.kind === "none") {
		const body = text.replace(/\s+$/, "");
		return body ? `${body}${eol}${eol}${regionLines.join(eol)}${eol}` : `${regionLines.join(eol)}${eol}`;
	}
	return [...lines.slice(0, found.start), ...regionLines, ...lines.slice(found.end + 1)].join(eol);
}

/** Text of a new companion note: frontmatter (already YAML) and the region; the user writes below. */
export function newCompanionText(yaml: string, region: string): string {
	const fm = yaml.endsWith("\n") ? yaml : `${yaml}\n`;
	return `---\n${fm}---\n${region}\n\n`;
}

// ------------------------------------------------------------------- ownership

/**
 * Whether an existing note that carries a `notebook-id` may be used as the companion of a notebook.
 * - `link`: where the note's `notebook` link resolves: to this notebook, to another notebook, or to none.
 * - `sameId`: the note's id is this notebook's document id.
 * - `atOwnPath`: the note sits at one of this notebook's own companion paths (derived from its file path).
 *
 * `"if-unique"`: only when no other notebook in the vault has the same id. A file copy of a notebook keeps the
 * id, so a note found elsewhere by its id alone could be the original's: the copy must not take it over.
 */
export function companionClaim(link: "this" | "other" | "none", sameId: boolean, atOwnPath: boolean): "yes" | "no" | "if-unique" {
	if (link === "this") return "yes";
	if (link === "other" || !sameId) return "no";
	return atOwnPath ? "yes" : "if-unique";
}

// ------------------------------------------------------------------- whole note

/** Where a note's frontmatter is: offsets of its contents, without the `---` lines (Obsidian's FrontMatterInfo). */
export interface FrontmatterBlock {
	exists: boolean;
	from: number;
	to: number;
}

/** The YAML side of an update, injected so this module stays free of 'obsidian'. */
export interface CompanionTextDeps {
	frontmatterInfo(text: string): FrontmatterBlock;
	/** The frontmatter as an object ({} when empty); null when it is not valid YAML or not a mapping. */
	parseFrontmatter(yaml: string): Record<string, unknown> | null;
	stringify(data: Record<string, unknown>): string;
}

export type CompanionTextUpdate =
	| { kind: "unchanged" }
	| { kind: "changed"; text: string }
	/** The frontmatter is not valid YAML: the note is left alone. */
	| { kind: "yaml" }
	/** The region markers are missing, repeated or out of order: the note is left alone. */
	| { kind: "markers" };

/**
 * The whole companion note after an update, so it can be written once (one `vault.process`): the plugin-owned
 * properties merged into the frontmatter (mergeProperties) and the generated region replaced (mergeRegion).
 * User properties, user text and the frontmatter as written are kept byte for byte when no plugin-owned
 * property changed; otherwise only the frontmatter block is re-serialized, as `processFrontMatter` would.
 */
export function updateCompanionText(
	text: string, content: CompanionContent, region: string | ((ownedTags: readonly string[]) => string), deps: CompanionTextDeps,
): CompanionTextUpdate {
	const info = deps.frontmatterInfo(text);
	const current = info.exists ? deps.parseFrontmatter(text.slice(info.from, info.to)) : {};
	if (current === null) return { kind: "yaml" };
	if (regionStatus(text) === "broken") return { kind: "markers" };
	// What the last update owned: read before the region (which stores it) is replaced.
	const previous = readRegionState(text);
	const { properties: nextProps, ownedTags } = mergeCompanion(current, content, previous);
	const merged = mergeRegion(text, typeof region === "function" ? region(ownedTags) : region);
	if (merged === null) return { kind: "markers" };
	let out = merged;
	if (!sameProperties(current, nextProps)) {
		const eol = text.includes("\r\n") ? "\r\n" : "\n";
		const yaml = deps.stringify(nextProps).replace(/\r?\n/g, eol).replace(/(\r?\n)+$/, "");
		const at = deps.frontmatterInfo(merged);
		if (at.exists) {
			const tail = merged.slice(at.to);
			out = `${merged.slice(0, at.from)}${yaml}${/^\r?\n/.test(tail) ? "" : eol}${tail}`;
		} else {
			out = `---${eol}${yaml}${eol}---${eol}${merged}`;
		}
	}
	return out === text ? { kind: "unchanged" } : { kind: "changed", text: out };
}

// ------------------------------------------------------------------- properties

/** Tags as found in frontmatter: a list, or one string with commas or spaces; without `#`. */
export function readTags(value: unknown): string[] {
	const raw: unknown[] = Array.isArray(value) ? value : typeof value === "string" ? value.split(/[,\s]+/) : [];
	return raw.filter((t): t is string => typeof t === "string").map((t) => t.trim().replace(/^#+/, "")).filter((t) => t.length > 0);
}

/**
 * The entries of a `tags` value that `readTags` does not read (numbers such as an unquoted `2026`, booleans, nulls,
 * nested lists, empty strings), as they are. An update keeps them: it must not lose what the person wrote.
 */
export function unreadTags(value: unknown): unknown[] {
	if (Array.isArray(value)) return value.filter((t) => typeof t !== "string" || t.trim().replace(/^#+/, "").length === 0);
	return typeof value === "number" || typeof value === "boolean" ? [value] : [];
}

export interface MergedCompanion {
	/** The frontmatter after the update. */
	properties: Record<string, unknown>;
	/** Tags the plugin added to the note: stored on the start marker, the only ones it may remove later. */
	ownedTags: string[];
}

/** The frontmatter after an update (see `mergeCompanion`). */
export function mergeProperties(current: Readonly<Record<string, unknown>>, content: CompanionContent, previous: RegionState | null): Record<string, unknown> {
	return mergeCompanion(current, content, previous).properties;
}

/**
 * The frontmatter after an update, and the tags the plugin owns in it. `current` is what the note has now; `previous`
 * the state of the last update (null when unknown: then nothing is removed, only added or overwritten, and a tag the
 * note already has counts as the person's). Key order of `current` is kept; new keys are appended in generator order.
 * `tags` follows the rule of `computeSharedTags` (model/tags.ts).
 */
export function mergeCompanion(current: Readonly<Record<string, unknown>>, content: CompanionContent, previous: RegionState | null): MergedCompanion {
	const owned = new Set([...(previous?.keys ?? []), ...Object.keys(content.properties)]);
	owned.delete(TAGS_KEY);
	const next: Record<string, unknown> = {};
	for (const [key, value] of Object.entries(current)) {
		if (key === TAGS_KEY) {
			next[key] = value;
			continue;
		}
		if (!owned.has(key)) next[key] = value;
		else if (Object.prototype.hasOwnProperty.call(content.properties, key)) next[key] = content.properties[key];
		// else: owned before, no value now → removed.
	}
	for (const [key, value] of Object.entries(content.properties)) {
		if (!Object.prototype.hasOwnProperty.call(next, key)) next[key] = value;
	}

	const hadTags = Object.prototype.hasOwnProperty.call(current, TAGS_KEY);
	const raw = current[TAGS_KEY];
	const currentTags = readTags(raw);
	// Entries that are not tag names (`2026` read by YAML as a number…) are not the plugin's: kept as they are, last.
	const extras = unreadTags(raw);
	const shared = computeSharedTags(content.tags, currentTags, previous?.tags ?? null);
	if (shared.tags.length > 0 || extras.length > 0) {
		const wanted = [...shared.tags, ...extras];
		const same = Array.isArray(raw)
			? JSON.stringify(raw) === JSON.stringify(wanted)
				// Only where the kept entries sit differs: the note's own order stays.
				|| (extras.length > 0 && JSON.stringify(raw.filter((t) => !extras.includes(t))) === JSON.stringify(shared.tags))
			: shared.tags.length === 0;
		if (!same) next[TAGS_KEY] = wanted;
	} else if (hadTags && currentTags.length > 0) {
		// Every tag left was ours: drop the property. (An empty `tags:` the user wrote stays.)
		delete next[TAGS_KEY];
	}
	return { properties: next, ownedTags: shared.owned };
}

/** A YAML parser may read an unquoted timestamp as a Date: compare it as the string the generator writes. */
function plain(_key: string, value: unknown): unknown {
	return typeof value === "string" && /^\d{4}-\d\d-\d\dT[\d:.]+Z$/.test(value) ? value.replace(/\.000Z$/, "Z") : value;
}

/** True when two frontmatter objects are the same, key order included. */
export function sameProperties(a: Readonly<Record<string, unknown>>, b: Readonly<Record<string, unknown>>): boolean {
	return JSON.stringify(a, plain) === JSON.stringify(b, plain);
}
